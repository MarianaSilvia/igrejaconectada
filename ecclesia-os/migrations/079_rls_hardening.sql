CREATE POLICY networks_app_scope ON networks FOR SELECT TO ecclesia_app USING (EXISTS (SELECT 1 FROM network_members nm WHERE nm.network_id=networks.id AND nm.user_id=actor_id()) OR EXISTS (SELECT 1 FROM churches c WHERE c.network_id=networks.id AND c.id=tenant_id()));
CREATE POLICY regions_app_scope ON regions FOR SELECT TO ecclesia_app USING (network_id IN (SELECT c.network_id FROM churches c WHERE c.id=tenant_id()));
CREATE POLICY churches_app_scope ON churches FOR SELECT TO ecclesia_app USING (id=tenant_id() OR network_id IN (SELECT nm.network_id FROM network_members nm WHERE nm.user_id=actor_id()));
CREATE POLICY campuses_app_scope ON campuses FOR SELECT TO ecclesia_app USING (church_id=tenant_id());
CREATE POLICY users_app_scope ON users FOR SELECT TO ecclesia_app USING (id=actor_id() OR EXISTS (SELECT 1 FROM memberships m WHERE m.user_id=users.id AND m.church_id=tenant_id()));
CREATE POLICY memberships_app_scope ON memberships FOR SELECT TO ecclesia_app USING (church_id=tenant_id());
CREATE POLICY network_members_app_scope ON network_members FOR SELECT TO ecclesia_app USING (network_id IN (SELECT c.network_id FROM churches c WHERE c.id=tenant_id()) OR user_id=actor_id());
CREATE POLICY sessions_app_scope ON sessions FOR ALL TO ecclesia_app USING (user_id=actor_id()) WITH CHECK (user_id=actor_id());
CREATE POLICY login_challenges_app_scope ON login_challenges FOR ALL TO ecclesia_app USING (user_id=actor_id()) WITH CHECK (user_id=actor_id());
CREATE POLICY access_grants_app_scope ON access_grants FOR SELECT TO ecclesia_app USING (church_id=tenant_id() AND (user_id=actor_id() OR local_role()='admin'));
CREATE POLICY transfers_app_scope ON transfers FOR SELECT TO ecclesia_app USING ((source_church_id=tenant_id() OR target_church_id=tenant_id()) AND local_role() IS NOT NULL);
CREATE POLICY pix_events_app_scope ON pix_events FOR SELECT TO ecclesia_app USING (church_id=tenant_id() AND can_access('finance'));
